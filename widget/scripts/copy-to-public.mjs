// Copies the built widget UMD bundle into the main app's public/ folder
// (kept for local/dev convenience) AND generates a src/ module embedding the
// same content as a string constant. The actual production route
// (src/app/widget.js/route.ts) serves from that generated module instead of
// the static public/ file - Vercel's static-asset serving for /public
// ignores both next.config.js's and vercel.json's headers config for this
// file (confirmed by testing - Cache-Control never changed no matter which
// one we set), so a real dynamic route is the only way to reliably control
// its cache headers. Runs automatically after `npm run build` via the
// postbuild script in package.json.

import { copyFileSync, existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));

const source = resolve(__dirname, '..', 'dist', 'widget.umd.js');
const publicDestination = resolve(__dirname, '..', '..', 'public', 'widget.js');
const generatedDir = resolve(__dirname, '..', '..', 'src', 'generated');
const generatedDestination = resolve(generatedDir, 'widget-bundle.ts');

if (!existsSync(source)) {
  console.error(`[postbuild] Build output not found at ${source}. Skipping copy to public/.`);
  process.exit(1);
}

try {
  copyFileSync(source, publicDestination);
  console.log(`[postbuild] Copied widget.umd.js -> ${publicDestination}`);

  const code = readFileSync(source, 'utf8');
  mkdirSync(generatedDir, { recursive: true });
  const fileContents = [
    '// Auto-generated by widget/scripts/copy-to-public.mjs - do not edit by hand.',
    '// Served by src/app/widget.js/route.ts with explicit cache headers.',
    `export const WIDGET_JS_CONTENT = ${JSON.stringify(code)};`,
    '',
  ].join('\n');
  writeFileSync(generatedDestination, fileContents);
  console.log(`[postbuild] Wrote widget bundle -> ${generatedDestination}`);
  console.log('[postbuild] This is the file served at https://modlyai.tech/widget.js. Redeploy the main app to publish it.');
} catch (error) {
  console.error('[postbuild] Failed to copy widget build into public/ or src/generated:', error);
  process.exit(1);
}
